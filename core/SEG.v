module	SEG(	BCD_I,
					SEG_O
				);
input	[3:0]	BCD_I;
output	[6:0]	SEG_O;
reg		[6:0]	SEG_O;

always @(BCD_I[3:0])
begin
	case (BCD_I[3:0])
		4'b 0000: 
			SEG_O[6:0]	<= 7'b 100_0000;
		4'b 0001: 
			SEG_O[6:0]	<= 7'b 111_1001;
		4'b 0010: 
			SEG_O[6:0]	<= 7'b 010_0100;
		4'b 0011: 
			SEG_O[6:0]	<= 7'b 011_0000;
		4'b 0100: 
			SEG_O[6:0]	<= 7'b 001_1001;
		4'b 0101: 
			SEG_O[6:0]	<= 7'b 001_0010;
		4'b 0110: 
			SEG_O[6:0]	<= 7'b 000_0010;
		4'b 0111: 
			SEG_O[6:0]	<= 7'b 101_1000;
		4'b 1000: 
			SEG_O[6:0]	<= 7'b 000_0000;
		4'b 1001: 
			SEG_O[6:0]	<= 7'b 001_0000;
		4'b 1010: 
			SEG_O[6:0]	<= 7'b 000_1000;
		4'b 1011: 
			SEG_O[6:0]	<= 7'b 000_0011;
		4'b 1100: 
			SEG_O[6:0]	<= 7'b 100_0110;
		4'b 1101: 
			SEG_O[6:0]	<= 7'b 010_0001;
		4'b 1110: 
			SEG_O[6:0]	<= 7'b 000_0110;
		4'b 1111: 
			SEG_O[6:0]	<= 7'b 000_1110;
		default:
			SEG_O[6:0]	<= 7'b 100_0000;
	endcase
end

endmodule
